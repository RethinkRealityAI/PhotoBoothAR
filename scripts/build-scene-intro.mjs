/**
 * build-scene-intro.mjs — keeps the keepsake-film scene intro on the SAME
 * opening maths as the live card, and bakes render-ready bundles.
 *
 *   node scripts/build-scene-intro.mjs
 *     Regenerates hyperframes/card-scene-intro/scene-frame.js: an IIFE build of
 *     the pure src/lib/cardDesigns.ts (sceneFrame, irisPath, CARD_DESIGNS…)
 *     exposed as `window.SceneIntro`. Committed; src/lib/sceneIntroDrift.test.ts
 *     goes red when it no longer matches the source.
 *
 *   node scripts/build-scene-intro.mjs --bake <payload.json> <outDir>
 *     Copies the composition + gsap + scene-frame.js + Geist + that design's art into
 *     <outDir>, with the payload baked into the `si-payload-data` slot (the
 *     same pre-script channel keepsake-film uses: HyperFrames variables land
 *     AFTER the synchronous build). Then: npx hyperframes render <outDir>.
 *     payload = { design, title, recipient }.
 */
import { buildSync } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COMP = join(ROOT, 'hyperframes/card-scene-intro');
const OUT_JS = join(COMP, 'scene-frame.js');
const SLOT_RE = /<script id="si-payload-data">[\s\S]*?<\/script>/;

/** The generated module's text. Exported for the drift test. */
export function sceneFrameBundle() {
  const res = buildSync({
    entryPoints: [join(ROOT, 'src/lib/cardDesigns.ts')],
    bundle: true,
    format: 'iife',
    globalName: 'SceneIntro',
    platform: 'browser',
    target: 'es2019',
    write: false,
    legalComments: 'none',
    charset: 'utf8',
  });
  const banner =
    '/* GENERATED by scripts/build-scene-intro.mjs from src/lib/cardDesigns.ts — do not edit. */\n';
  return banner + res.outputFiles[0].text;
}

export function bake(payload, outDir) {
  if (!payload || typeof payload.design !== 'string' || !/^[a-z0-9-]+$/.test(payload.design)) {
    throw new Error('payload.design must be a design id');
  }
  const html = readFileSync(join(COMP, 'index.html'), 'utf8');
  if (!SLOT_RE.test(html)) throw new Error('si-payload-data slot not found');
  const literal = JSON.stringify(JSON.stringify({ ...payload, artBase: './art' })).replace(/<\/(script)/gi, '<\\/$1');
  mkdirSync(join(outDir, 'art', payload.design), { recursive: true });
  writeFileSync(
    join(outDir, 'index.html'),
    html.replace(SLOT_RE, `<script id="si-payload-data">window.__SCENE_INTRO__ = JSON.parse(${literal});</script>`),
  );
  copyFileSync(join(ROOT, 'hyperframes/keepsake-film/gsap.min.js'), join(outDir, 'gsap.min.js'));
  copyFileSync(OUT_JS, join(outDir, 'scene-frame.js'));
  mkdirSync(join(outDir, 'fonts'), { recursive: true });
  copyFileSync(join(ROOT, 'public/fonts/geist-var-latin.woff2'), join(outDir, 'fonts', 'geist-var-latin.woff2'));
  for (const f of ['gate', 'back', 'mid']) {
    copyFileSync(join(ROOT, 'public/card-designs', payload.design, `${f}.webp`), join(outDir, 'art', payload.design, `${f}.webp`));
  }
  return join(outDir, 'index.html');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  if (args[0] === '--bake') {
    const [, payloadPath, outDir] = args;
    if (!payloadPath || !outDir) {
      console.error('usage: node scripts/build-scene-intro.mjs --bake <payload.json> <outDir>');
      process.exit(1);
    }
    console.log('baked →', bake(JSON.parse(readFileSync(resolve(payloadPath), 'utf8')), resolve(outDir)));
  } else {
    writeFileSync(OUT_JS, sceneFrameBundle());
    console.log('wrote', OUT_JS);
  }
}
